#!/usr/bin/env node
/**
 * Starts the local Supabase (Docker), points `next dev` at it and seeds it. `next dev` refuses to start
 * against a remote Supabase (next.config.js), so run this once before `npm run dev`.
 *
 *   npm run db:local     start + write .env.development.local + seed (idempotent)
 *   supabase stop        stop it (data is kept) · supabase db reset: rebuild from migrations, then db:local again
 *
 * Doc: docs/claude/base-local.md
 */
import { execFileSync, spawnSync } from 'node:child_process'
import { randomBytes } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parseEnv } from 'node:util'
import { SUPABASE_CREDENTIAL_VARS, esLoopback } from './lib/supabase-ref.mjs'
import { TEST_E2E_EMAIL } from './test-db/seed.mjs'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const ENV_FILE = join(ROOT, '.env.development.local')
// Only Postgres, auth, PostgREST and the gateway run: supabase-js needs the last three, the seed talks to Postgres.
const UNUSED_SERVICES = ['storage-api', 'imgproxy', 'postgres-meta', 'studio', 'mailpit', 'realtime', 'edge-runtime', 'logflare', 'vector', 'supavisor']

/** Every Supabase credential var gets a value, so none falls through to the prod one in .env.local. */
export function devEnv(status, password) {
  const local = {
    NEXT_PUBLIC_SUPABASE_URL: status.API_URL,
    SUPABASE_URL: status.API_URL,
    NEXT_PUBLIC_SUPABASE_ANON_KEY: status.ANON_KEY,
    SUPABASE_SERVICE_ROLE_KEY: status.SERVICE_ROLE_KEY,
  }
  const env = Object.fromEntries(SUPABASE_CREDENTIAL_VARS.map(name => [name, local[name] ?? '']))
  return { ...env, TEST_E2E_USER_PASSWORD: password }
}

function main() {
  console.log('→ supabase start (la primera vez descarga las imágenes de Docker)')
  execFileSync('supabase', ['start', '-x', UNUSED_SERVICES.join(',')], { cwd: ROOT, stdio: 'inherit' })
  const status = parseEnv(execFileSync('supabase', ['status', '-o', 'env'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] }))
  if (!esLoopback(status.API_URL)) throw new Error(`supabase status devolvió API_URL=${status.API_URL}, que no es local`)

  const previous = existsSync(ENV_FILE) ? parseEnv(readFileSync(ENV_FILE, 'utf8')) : {}
  const env = devEnv(status, previous.TEST_E2E_USER_PASSWORD || randomBytes(18).toString('base64url'))
  writeFileSync(ENV_FILE, [
    '# Generated by `npm run db:local`: next dev uses the local Supabase. Gitignored, never commit.',
    ...Object.entries(env).map(([k, v]) => `${k}=${v}`),
    '',
  ].join('\n'))
  console.log('→ .env.development.local escrito')

  const seed = spawnSync(process.execPath, [join(ROOT, 'scripts', 'test-db', 'seed.mjs')], {
    cwd: ROOT,
    stdio: 'inherit',
    env: {
      ...process.env,
      ...env,
      TEST_SUPABASE_URL: env.NEXT_PUBLIC_SUPABASE_URL,
      TEST_SUPABASE_SERVICE_ROLE_KEY: env.SUPABASE_SERVICE_ROLE_KEY,
      TEST_SUPABASE_DB_URL: status.DB_URL,
    },
  })
  if (seed.status !== 0) throw new Error(`el seed falló (exit ${seed.status})`)

  console.log(`✔ Supabase local listo: API ${status.API_URL}`)
  console.log(`  Usuario de prueba: ${TEST_E2E_EMAIL} (contraseña en .env.development.local). Ahora: npm run dev`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main()
  } catch (e) {
    console.error(`✘ db:local: ${e.message}`)
    process.exitCode = 1
  }
}
